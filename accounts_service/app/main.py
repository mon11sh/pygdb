# JWT config setup from the shared gdb_common package (M-4: replaces the previous
# sys.path import of auth_service's security module).
from gdb_common.auth_dependencies import set_jwt_config

from app.config.settings import settings
from app.config.logging import setup_logging
from app.database.db import initialize_db, close_db
from app.api import account_routes, internal_accounts
from app.dependencies.internal_auth import verify_internal_api_key

# Configure logging
logger = setup_logging()


@asynccontextmanager
async def lifespan(app: FastAPI):
    """
    Manage application lifecycle.
    
    Handles startup and shutdown events.
    """
    # Startup
    logger.info("🚀 Starting Accounts Service...")
    
    # Initialize JWT config for authorization
    try:
        set_jwt_config(
            secret_key=settings.jwt_secret_key,
            algorithm=settings.jwt_algorithm,
            disable_auth=settings.disable_auth,
            public_key=getattr(settings, "JWT_PUBLIC_KEY", ""),  # RS256 verify (C-1)
        )
        logger.info("✅ JWT config initialized")
    except Exception as e:
        logger.error(f"Failed to initialize JWT config: {str(e)}")
        raise
    
    await initialize_db(
        str(settings.database_url),
        min_size=settings.min_db_pool_size,
        max_size=settings.max_db_pool_size
    )
    logger.info("✅ Database initialized")
    
    yield
    
    # Shutdown
    logger.info("🛑 Shutting down Accounts Service...")
    await close_db()
    logger.info("✅ Accounts Service stopped")


# Create FastAPI app
app = FastAPI(
    title=settings.app_name,
    description="Microservice for managing bank accounts",
    version=settings.app_version,
    openapi_url=f"{settings.api_prefix}/openapi.json",
    docs_url=f"{settings.api_prefix}/docs",
    redoc_url=f"{settings.api_prefix}/redoc",
    lifespan=lifespan
)

# Add OpenAPI security scheme for Bearer token
def custom_openapi():
    """Custom OpenAPI schema with Bearer token security."""
    if app.openapi_schema:
        return app.openapi_schema
    
    # Get the default OpenAPI schema generated by FastAPI
    openapi_schema = get_openapi(
        title=settings.app_name,
        version=settings.app_version,
        description="Microservice for managing bank accounts",
        routes=app.routes,
    )
    
    # Add Bearer token security scheme
    openapi_schema["components"]["securitySchemes"] = {
        "Bearer": {
            "type": "http",
            "scheme": "bearer",
            "bearerFormat": "JWT",
            "description": "JWT Bearer token. Get from Auth Service /login endpoint",
        }
    }
    
    # Apply security to all endpoints
    openapi_schema["security"] = [{"Bearer": []}]
    
    app.openapi_schema = openapi_schema
    return app.openapi_schema

app.openapi = custom_openapi

# Add CORS middleware
app.add_middleware(
    CORSMiddleware,
    allow_origins=settings.CORS_ALLOWED_ORIGINS,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Add trusted host middleware
app.add_middleware(
    TrustedHostMiddleware,
    allowed_hosts=[h.strip() for h in settings.ALLOWED_HOSTS.split(",") if h.strip()]
)


# Include routers
app.include_router(
    account_routes.router,
    prefix=settings.api_prefix,
    tags=["accounts"]
)

app.include_router(
    internal_accounts.router,
    prefix=f"{settings.api_prefix}/internal",
    tags=["internal"],
    dependencies=[Depends(verify_internal_api_key)]
)


@app.get("/health", tags=["health"])
async def health_check():
    """
    Health check endpoint.
    
    Returns:
        dict: Service health status
    """
    return {
        "status": "healthy",
        "service": settings.app_name,
        "version": settings.app_version,
        "environment": settings.environment
    }


@app.get("/", tags=["root"])
async def root():
    """
    Root endpoint.
    
    Returns:
        dict: Service information
    """
    return {
        "service": settings.app_name,
        "version": settings.app_version,
        "docs": f"http://localhost:{settings.port}{settings.api_prefix}/docs"
    }


