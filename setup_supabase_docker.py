#!/usr/bin/env python3
"""
GDB (Docker) — point the Docker stack at your Supabase database with ONE command.

Writes the root `.env` that docker-compose.supabase.yml reads, filling BOTH the
full connection URL (used by the auth / users / accounts services) AND the split
DB_* fields (used by the transactions service's asyncpg path) from a SINGLE
Supabase URI — so you can't update one and forget the other (a common mistake
that makes only the transactions service fail with "tenant/user ... not found").

HOW TO USE
----------
1) In Supabase: Project -> "Connect" -> "Session pooler" (port 5432) -> copy the URI:
   postgresql://postgres.abcd:YOURPASSWORD@aws-1-ap-south-1.pooler.supabase.com:5432/postgres
2) Run it (put the whole URI in quotes):
   python setup_supabase_docker.py "postgresql://postgres.abcd:YOURPASSWORD@aws-1-ap-south-1.pooler.supabase.com:5432/postgres"
3) Start Docker:
   python docker_up.py supabase

Then open http://localhost:3000 and log in with  admin / Welcome@1.

TIP: use a Supabase database password made of ONLY letters and numbers, so the
URI has no special characters to worry about.
"""

import sys
from pathlib import Path
from urllib.parse import urlparse, unquote

try:  # so emoji in the output never crash a Windows (cp1252) console
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

ROOT = Path(__file__).parent.resolve()
ENV = ROOT / ".env"


def parse(conn: str) -> dict:
    """Split a Supabase/Postgres URI into its user/password/host/port/db parts."""
    u = urlparse(conn.strip())
    if not (u.scheme or "").startswith("postgres") or not u.hostname:
        raise SystemExit(
            "❌ That does not look like a Supabase/Postgres URI.\n"
            "   Expected: postgresql://USER:PASSWORD@HOST:5432/postgres\n"
            "   (Supabase → Connect → Session pooler)"
        )
    return {
        "user": unquote(u.username or "postgres"),
        "password": unquote(u.password or ""),
        "host": u.hostname,
        "port": str(u.port or 5432),
        "db": (u.path or "/postgres").lstrip("/") or "postgres",
    }


def main() -> None:
    if len(sys.argv) < 2:
        sys.exit(__doc__)

    conn = sys.argv[1].strip()
    p = parse(conn)

    print("=" * 62)
    print("🟢 GDB (Docker) → Supabase setup")
    print(f"   host={p['host']}  port={p['port']}  db={p['db']}  user={p['user']}")
    print("=" * 62)

    lines = [
        "# Supabase-over-Docker settings — generated by setup_supabase_docker.py.",
        "# Read by docker-compose.supabase.yml. Do NOT commit this file.",
        "",
        f"SUPABASE_DATABASE_URL={conn}",
        f"SUPABASE_DB_HOST={p['host']}",
        f"SUPABASE_DB_PORT={p['port']}",
        f"SUPABASE_DB_USER={p['user']}",
        f"SUPABASE_DB_PASSWORD={p['password']}",
        f"SUPABASE_DB_NAME={p['db']}",
        "",
    ]
    ENV.write_text("\n".join(lines), encoding="utf-8")
    print(f"✅ Wrote {ENV}  (URL + all DB_* fields, kept in sync)")
    print("=" * 62)
    print("🎉 .env ready for Docker Supabase.")
    print("Next steps:")
    print("  1. python docker_up.py supabase      (builds + starts everything)")
    print("  2. Open http://localhost:3000 and log in:  admin / Welcome@1")
    print("=" * 62)


if __name__ == "__main__":
    main()
