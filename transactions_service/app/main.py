@asynccontextmanager
async def lifespan(app: FastAPI):
    """
    FastAPI lifespan context manager.
    Handles startup and shutdown events properly.
    """
    # Startup
    logger.info("🚀 Starting Transaction Service")
    logger.info(f"📊 Database: {settings.DB_HOST}:{settings.DB_PORT}/{settings.DB_NAME}")
    logger.info(f"💰 Account Service: {settings.ACCOUNT_SERVICE_URL}")
    
    # Initialize JWT configuration for authorization
    try:
        set_jwt_config(settings.JWT_SECRET_KEY, settings.JWT_ALGORITHM,
                       public_key=getattr(settings, "JWT_PUBLIC_KEY", ""))  # RS256 verify (C-1)
        logger.info("✅ JWT configuration initialized for RBAC")
    except Exception as e:
        logger.error(f"❌ Failed to initialize JWT config: {str(e)}")
        raise
    
    try:
        await database.initialize()
        logger.info("✅ Database connection pool initialized")
    except Exception as e:
        logger.error(f"❌ Failed to initialize database: {str(e)}")
        raise
    
    yield
    
    # Shutdown
    logger.info("👋 Shutting down Transaction Service")
    try:
        await database.close()
        logger.info("✅ Database connection pool closed")
    except Exception as e:
        logger.error(f"❌ Error closing database: {str(e)}")


