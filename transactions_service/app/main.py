# Global exception handler for TransactionException
@app.exception_handler(TransactionException)
async def transaction_exception_handler(request, exc: TransactionException):
    """Handle all transaction-related exceptions."""
    log_business_logic_error("transactions_service", exc, operation=request.url.path, details={"error_code": exc.error_code})
    
    return JSONResponse(
        status_code=exc.http_code,
        content={
            "error_code": exc.error_code,
            "message": exc.message,
            "status": "error",
        },
    )


# Global exception handler for unhandled exceptions
@app.exception_handler(Exception)
async def general_exception_handler(request, exc: Exception):
    """Handle all unhandled exceptions."""
    log_error("transactions_service", exc, endpoint=str(request.url), severity="CRITICAL")

    return JSONResponse(
        status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
        content={
            "error_code": "INTERNAL_ERROR",
            "message": "Internal server error",
            "status": "error",
        },
    )


